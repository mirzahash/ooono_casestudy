-- New tables: old RAW.DRIVES/WARNINGS/USERS snapshots remain untouched.
CREATE STAGE IF NOT EXISTS REPORT_LOAD_STAGE;
CREATE TABLE IF NOT EXISTS DRIVE_REPORTS (
    REPORT_KEY VARCHAR(64) NOT NULL,
    SOURCE_ID VARCHAR,
    SOURCE_RECEIVED_AT TIMESTAMP_TZ,
    PAYLOAD VARIANT NOT NULL,
    RECORD_HASH VARCHAR(64) NOT NULL,
    BATCH_ID VARCHAR(64) NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    INGESTED_AT TIMESTAMP_TZ NOT NULL
);
CREATE TABLE IF NOT EXISTS WARNING_REPORTS LIKE DRIVE_REPORTS;
CREATE TABLE IF NOT EXISTS USER_PROFILES LIKE DRIVE_REPORTS;
CREATE TABLE IF NOT EXISTS INGESTION_RUNS (
    BATCH_ID VARCHAR(64) NOT NULL,
    RECEIPT_CUTOFF TIMESTAMP_TZ NOT NULL,
    RECEIVED_SINCE TIMESTAMP_TZ,
    STATUS VARCHAR NOT NULL,
    LOADED_AT TIMESTAMP_TZ NOT NULL,
    COMPLETED_AT TIMESTAMP_TZ
);
