-- Existing database/schema/warehouse are selected by the connection.
-- No CREATE OR REPLACE, TRUNCATE, or business-level deduplication.
CREATE STAGE IF NOT EXISTS INGESTION_STAGE;
CREATE TABLE IF NOT EXISTS DRIVES (
    SNAPSHOT_ID VARCHAR NOT NULL,
    SOURCE_ORDINAL NUMBER(38,0) NOT NULL,
    SOURCE_ID VARCHAR,
    SOURCE_RECEIVED_AT TIMESTAMP_TZ,
    PAYLOAD VARIANT NOT NULL,
    RECORD_HASH VARCHAR(64) NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    SOURCE_FILE_SHA256 VARCHAR(64) NOT NULL,
    INGESTED_AT TIMESTAMP_TZ NOT NULL
);
CREATE TABLE IF NOT EXISTS WARNINGS LIKE DRIVES;
CREATE TABLE IF NOT EXISTS USERS LIKE DRIVES;
CREATE TABLE IF NOT EXISTS INGESTION_SNAPSHOTS (
    SNAPSHOT_ID VARCHAR NOT NULL,
    MANIFEST VARIANT NOT NULL,
    STATUS VARCHAR NOT NULL,
    LOAD_STARTED_AT TIMESTAMP_TZ,
    LOAD_COMPLETED_AT TIMESTAMP_TZ
);
