-- Run once with a setup administrator; routine transformations use OOONO_DBT.
USE DATABASE OOONO_CASE;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;
CREATE ROLE IF NOT EXISTS OOONO_DBT;
GRANT USAGE ON WAREHOUSE OOONO_WH TO ROLE OOONO_DBT;
GRANT USAGE ON DATABASE OOONO_CASE TO ROLE OOONO_DBT;
GRANT USAGE ON SCHEMA OOONO_CASE.RAW TO ROLE OOONO_DBT;
GRANT SELECT ON TABLE OOONO_CASE.RAW.DRIVES TO ROLE OOONO_DBT;
GRANT SELECT ON TABLE OOONO_CASE.RAW.WARNINGS TO ROLE OOONO_DBT;
GRANT SELECT ON TABLE OOONO_CASE.RAW.USERS TO ROLE OOONO_DBT;
GRANT SELECT ON TABLE OOONO_CASE.RAW.INGESTION_SNAPSHOTS TO ROLE OOONO_DBT;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA OOONO_CASE.STAGING TO ROLE OOONO_DBT;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA OOONO_CASE.ANALYTICS TO ROLE OOONO_DBT;
-- User-role assignment uses the authenticated user object in scripts/setup_dbt.py.
